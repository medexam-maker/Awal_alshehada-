import crypto from 'node:crypto';
import { argon2id, argon2Verify } from 'hash-wasm';

/**
 * Hash a plaintext password using Argon2id via hash-wasm (WASM implementation).
 * C7 §4.3: "Argon2id is the required preferred password-hashing algorithm."
 * Uses RFC-compliant Argon2id parameters (m=64MB, t=3 passes, p=4 parallelism).
 */
export async function hashPassword(password: string): Promise<string> {
  const salt = crypto.randomBytes(16);
  return argon2id({
    password,
    salt,
    iterations: 3,
    memorySize: 65536,
    parallelism: 4,
    hashLength: 32,
    outputType: 'encoded',
  });
}

/**
 * Verify a plaintext password against an Argon2id hash using library primitive.
 * C7 §4.3: "Password verification MUST use constant-time-safe library primitives."
 * Fully backward-compatible with PHC strings generated by both native argon2 and hash-wasm.
 */
export async function verifyPassword(hash: string, password: string): Promise<boolean> {
  try {
    return await argon2Verify({
      password,
      hash,
    });
  } catch {
    return false;
  }
}

